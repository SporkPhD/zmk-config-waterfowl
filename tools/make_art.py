"""Draws the duck and the Mac modifier icons for the screens and writes them to
src/art.c as 1-bit bitmaps (one string per row, '#' = lit pixel).

Run from the repo root:  python3 tools/make_art.py
"""
import json
import math
import sys

# ---- Duck, drawn upright for the right screen (portrait, 56 x 64) ----
DW, DH = 56, 64


def duck_pixel(x, y):
    cx, cy = x + 0.5, y + 0.5
    def in_ellipse(ex, ey, rx, ry):
        return ((cx - ex) / rx) ** 2 + ((cy - ey) / ry) ** 2 <= 1
    def in_triangle(a, b, c):
        def side(p, q):
            return (q[0] - p[0]) * (cy - p[1]) - (q[1] - p[1]) * (cx - p[0])
        s1, s2, s3 = side(a, b), side(b, c), side(c, a)
        return (s1 >= 0 and s2 >= 0 and s3 >= 0) or (s1 <= 0 and s2 <= 0 and s3 <= 0)

    eye = in_ellipse(38.5, 12.5, 1.8, 1.8)
    # Wing: a dark curve along the lower side of the body.
    wing = in_ellipse(24, 38, 15, 8) and not in_ellipse(24, 38, 13.4, 6.6) and cy >= 39 and cx >= 12
    head = in_ellipse(35, 15, 10, 10)
    bill = in_triangle((43, 11.5), (55, 15.5), (43, 19.5))
    neck = 27 <= cx <= 40 and 20 <= cy <= 36
    body = in_ellipse(28, 42, 26, 13)
    tail = in_triangle((1, 29), (12, 35), (7, 46))
    duck = (head or bill or neck or body or tail) and not eye and not wing
    # Two rows of ripples under the duck.
    ripple = (cy // 1 in (58, 59) and (cx // 9) % 2 == 0) or (cy // 1 in (62, 63) and ((cx + 4) // 9) % 2 == 0)
    return duck or (ripple and cy > 56)


duck = ["".join("#" if duck_pixel(x, y) else "." for x in range(DW)) for y in range(DH)]

