def c_bitmap(name, rows):
    body = ",\n".join(f'    "{r}"' for r in rows)
    return f"const char *const {name}[] = {{\n{body},\n}};\n"


def main():
    out = ["/* Generated by tools/make_art.py. Edit that script, not this file. */\n",
           "#include \"art.h\"\n\n",
           c_bitmap("art_duck", duck), "\n"]
    for k, rows in ICONS.items():
        out += [c_bitmap(f"art_mod_{k}", rows), "\n"]
    with open("src/art.c", "w") as f:
        f.write("".join(out))
    if "--json" in sys.argv:
        print(json.dumps({"duck": duck, **{k: v for k, v in ICONS.items()}}))


if __name__ == "__main__":
    main()
